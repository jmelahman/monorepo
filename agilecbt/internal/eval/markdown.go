package eval

import (
	"bytes"
	"cmp"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// WriteMarkdown renders the pages as Markdown tables for the docs: one row
// per model, best scenario pass rate first, then pass rates by scenario tag.
// Reply times are left out: local and hosted latencies aren't comparable.
func WriteMarkdown(w io.Writer, pages []Page) error {
	pages = byPassRate(pages)
	var b strings.Builder
	b.WriteString("<!-- Generated by `agilecbt eval render -o <file>.md`; don't edit by hand. -->\n\n")
	b.WriteString("| Model | Scenarios | Safety | Tool recall | Phantom actions | Unwanted writes |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	for _, p := range pages {
		r, m := p.Report, p.Report.Metrics
		ok := scenarioRatio(r)
		safety := tagRatio(r, TagSafety)
		fmt.Fprintf(&b, "| `%s` | %d/%d | %s | %s | %s | %s |\n", r.Model, ok.N, ok.Of,
			mdRatio(safety, safety.Of > 0 && safety.N == safety.Of),
			mdRate(m.ToolRecall), mdRate(m.PhantomActions), mdRate(m.UnwantedMutations))
	}

	tags := map[string]bool{}
	for _, p := range pages {
		for _, s := range p.Report.Scenarios {
			for _, t := range s.Tags {
				tags[t] = true
			}
		}
	}
	names := make([]string, 0, len(tags))
	for t := range tags {
		names = append(names, t)
	}
	slices.Sort(names)
	b.WriteString("\nScenarios passed, by area:\n\n| Area |")
	for _, p := range pages {
		fmt.Fprintf(&b, " `%s` |", p.Report.Model)
	}
	b.WriteString("\n| --- |" + strings.Repeat(" --- |", len(pages)) + "\n")
	for _, t := range names {
		fmt.Fprintf(&b, "| %s |", t)
		for _, p := range pages {
			if r := tagRatio(p.Report, t); r.Of > 0 {
				fmt.Fprintf(&b, " %d/%d |", r.N, r.Of)
			} else {
				b.WriteString(" |")
			}
		}
		b.WriteString("\n")
	}

	var runs []string
	for _, p := range pages {
		r := p.Report
		n := 0
		if len(r.Scenarios) > 0 {
			n = r.Scenarios[0].Runs
		}
		runs = append(runs, fmt.Sprintf("`%s` %s, %d run(s) per scenario", r.Model, r.StartedAt.Format("2006-01-02"), n))
	}
	fmt.Fprintf(&b, "\nBenchmarked: %s.\n", strings.Join(runs, "; "))
	_, err := io.WriteString(w, b.String())
	return err
}

// SaveMarkdown writes the Markdown tables to path, creating its directory.
func SaveMarkdown(path string, pages []Page) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	var buf bytes.Buffer
	if err := WriteMarkdown(&buf, pages); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}

// byPassRate returns the pages sorted by scenarios passed, then safety
// scenarios passed, best first.
func byPassRate(pages []Page) []Page {
	pages = slices.Clone(pages)
	slices.SortStableFunc(pages, func(a, b Page) int {
		if c := cmpRate(scenarioRatio(b.Report), scenarioRatio(a.Report)); c != 0 {
			return c
		}
		return cmpRate(tagRatio(b.Report, TagSafety), tagRatio(a.Report, TagSafety))
	})
	return pages
}

// scenarioRatio counts the scenarios that met their threshold.
func scenarioRatio(r *Report) Ratio {
	n := 0
	for _, s := range r.Scenarios {
		if s.OK {
			n++
		}
	}
	return ratio(n, len(r.Scenarios))
}

func cmpRate(a, b Ratio) int {
	return cmp.Compare(a.Rate, b.Rate)
}

// tagRatio counts the scenarios with tag that met their threshold.
func tagRatio(r *Report, tag string) Ratio {
	var n, of int
	for _, s := range r.Scenarios {
		if slices.Contains(s.Tags, tag) {
			of++
			if s.OK {
				n++
			}
		}
	}
	return ratio(n, of)
}

func mdRatio(r Ratio, good bool) string {
	s := fmt.Sprintf("%d/%d", r.N, r.Of)
	if good {
		return s + " ✓"
	}
	return s
}

func mdRate(r Ratio) string {
	if r.Of == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%.0f%%", r.Rate*100)
}
