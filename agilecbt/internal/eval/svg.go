package eval

import (
	"bytes"
	"fmt"
	"html"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// SVG chart geometry: each row has the model name on one line and a bar
// per metric under it, so long hosted names don't widen the chart past the
// docs' content column.
const (
	svgTrackW = 120 // bar length
	svgValueW = 52  // room for the value after the bar
	svgGap    = 20
	svgPad    = 20
	svgRowH   = 46
	svgHeadH  = 50
)

var svgMetrics = []struct {
	name, color string
	value       func(*Report) (Ratio, string)
}{
	{"Scenarios passed", "#3b6fd4", func(r *Report) (Ratio, string) {
		s := scenarioRatio(r)
		return s, fmt.Sprintf("%d/%d", s.N, s.Of)
	}},
	{"Crisis safety", "#d2475f", func(r *Report) (Ratio, string) {
		s := tagRatio(r, TagSafety)
		return s, fmt.Sprintf("%d/%d", s.N, s.Of)
	}},
	{"Tool recall", "#1f9e8f", func(r *Report) (Ratio, string) {
		return r.Metrics.ToolRecall, mdRate(r.Metrics.ToolRecall)
	}},
}

// WriteSVG renders the pages as a bar chart for the docs: one row per model,
// sorted like the Markdown tables, with a bar per headline metric. Colors
// follow the reader's light or dark system theme.
func WriteSVG(w io.Writer, pages []Page) error {
	pages = byPassRate(pages)
	colW := svgTrackW + svgValueW + svgGap
	width := 2*svgPad + len(svgMetrics)*colW - svgGap
	height := 2*svgPad + svgHeadH + len(pages)*svgRowH - 6
	var b strings.Builder
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" role="img" aria-label="Coach benchmark results by model">`+"\n", width, height, width, height)
	b.WriteString(`<!-- Generated by agilecbt eval render -o <file>.svg; don't edit by hand. -->` + "\n")
	b.WriteString(`<style>` +
		`.bg{fill:#fbfbfd;stroke:#e3e5ea}.z{fill:#f1f2f6}.t{fill:#e1e3ea}` +
		`text{font-family:ui-sans-serif,system-ui,-apple-system,"Segoe UI",sans-serif;fill:#2b2f38;font-size:13px}` +
		`.m{font-family:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace;font-weight:600}.h{font-weight:600}` +
		`.v{font-variant-numeric:tabular-nums}.k{fill:#6b7180;font-size:12px}` +
		`@media (prefers-color-scheme:dark){.bg{fill:#1e2027;stroke:#2e313a}.z{fill:#252831}.t{fill:#343845}text{fill:#dfe2ea}.k{fill:#9aa0ad}}` +
		`</style>` + "\n")
	fmt.Fprintf(&b, `<rect class="bg" x=".5" y=".5" width="%d" height="%d" rx="10"/>`+"\n", width-1, height-1)

	for i, m := range svgMetrics {
		x := svgPad + i*colW
		fmt.Fprintf(&b, `<rect x="%d" y="%d" width="10" height="10" rx="2" fill="%s"/>`, x, svgPad+4, m.color)
		fmt.Fprintf(&b, `<text class="h" x="%d" y="%d">%s</text>`+"\n", x+16, svgPad+13, m.name)
	}
	fmt.Fprintf(&b, `<text class="k" x="%d" y="%d">Bars show the share passed, sorted by scenarios passed.</text>`+"\n", svgPad, svgPad+34)

	for row, p := range pages {
		y := svgPad + svgHeadH + row*svgRowH
		if row%2 == 0 {
			fmt.Fprintf(&b, `<rect class="z" x="%d" y="%d" width="%d" height="%d" rx="6"/>`, svgPad-10, y-4, width-2*svgPad+20, svgRowH-6)
		}
		fmt.Fprintf(&b, `<text class="m" x="%d" y="%d">%s</text>`, svgPad, y+12, html.EscapeString(p.Report.Model))
		for i, m := range svgMetrics {
			x := svgPad + i*colW
			r, label := m.value(p.Report)
			fmt.Fprintf(&b, `<rect class="t" x="%d" y="%d" width="%d" height="10" rx="5"/>`, x, y+21, svgTrackW)
			if r.Of > 0 && r.Rate > 0 {
				fw := float64(svgTrackW) * r.Rate
				fmt.Fprintf(&b, `<rect x="%d" y="%d" width="%.1f" height="10" rx="%.1f" fill="%s"/>`, x, y+21, fw, min(5, fw/2), m.color)
			}
			if r.Of == 0 {
				label = "n/a"
			}
			fmt.Fprintf(&b, `<text class="v" x="%d" y="%d">%s</text>`, x+svgTrackW+8, y+30, label)
		}
		b.WriteString("\n")
	}
	b.WriteString("</svg>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

// SaveSVG writes the chart to path, creating its directory.
func SaveSVG(path string, pages []Page) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	var buf bytes.Buffer
	if err := WriteSVG(&buf, pages); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}
